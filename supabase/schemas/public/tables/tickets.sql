CREATE TABLE "public"."tickets" (
  "id"                 uuid                     NOT NULL DEFAULT extensions.uuid_generate_v4(),
  "created_at"         timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
  "launch_week"        text                     NOT NULL,
  "user_id"            uuid                     NOT NULL,
  "email"              text,
  "name"               text,
  "username"           text,
  "referred_by"        text,
  "shared_on_twitter"  timestamp with time zone,
  "shared_on_linkedin" timestamp with time zone,
  "game_won_at"        timestamp with time zone,
  "ticket_number"      bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "metadata"           jsonb,
  "role"               text,
  "company"            text,
  "location"           text,
  CONSTRAINT "public_tickets_id_fkey" FOREIGN KEY (user_id) REFERENCES auth.users(id),
  CONSTRAINT "tickets_email_key" UNIQUE (email, launch_week),
  CONSTRAINT "tickets_launch_week_fkey" FOREIGN KEY (launch_week) REFERENCES public.launch_weeks(id),
  CONSTRAINT "tickets_pkey" PRIMARY KEY (id),
  CONSTRAINT "tickets_ticket_number_key" UNIQUE (ticket_number, launch_week),
  CONSTRAINT "tickets_user_id_fkey" FOREIGN KEY (user_id) REFERENCES auth.users(id),
  CONSTRAINT "tickets_username_key" UNIQUE (username, launch_week)
);

ALTER TABLE "public"."tickets"
  ENABLE ROW LEVEL SECURITY;

