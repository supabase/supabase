import { useParams } from 'common'
import dayjs from 'dayjs'
import { useState } from 'react'
import { toast } from 'sonner'
import { Button, copyToClipboard } from 'ui'
import { Admonition } from 'ui-patterns/Admonition'
import { PageContainer } from 'ui-patterns/PageContainer'
import {
  PageHeader,
  PageHeaderDescription,
  PageHeaderMeta,
  PageHeaderSummary,
  PageHeaderTitle,
} from 'ui-patterns/PageHeader'
import { PageSection, PageSectionContent } from 'ui-patterns/PageSection'

import { encodeModel } from './model.codec'
import { createExampleModel } from './model.schema'
import { ModelMetricPanel } from './ModelMetricPanel'
import { useModelFragment } from './useModelFragment'

export function ModelDashboard() {
  const { ref: projectRef } = useParams()
  const state = useModelFragment()
  const [isOpeningExample, setIsOpeningExample] = useState(false)
  const handleOpenExample = async () => {
    setIsOpeningExample(true)
    try {
      window.location.hash = await encodeModel(createExampleModel())
    } catch (error) {
      toast.error(error instanceof Error ? error.message : 'Failed to open example.')
    } finally {
      setIsOpeningExample(false)
    }
  }
  const handleCopyLink = () => {
    copyToClipboard(window.location.href)
  }

  return (
    <>
      <PageHeader size="large">
        <PageHeaderMeta>
          <PageHeaderSummary>
            <PageHeaderTitle>
              {state.status === 'ready' ? state.model.title : 'Dashboard Links'}
            </PageHeaderTitle>
            <PageHeaderDescription>A temporary view defined by its link</PageHeaderDescription>
          </PageHeaderSummary>
        </PageHeaderMeta>
      </PageHeader>
      <PageContainer size="large">
        <PageSection>
          <PageSectionContent>
            <div className="flex flex-col gap-6">
              {state.status === 'loading' && (
                <p role="status" className="text-sm text-foreground-light">
                  Opening dashboard link...
                </p>
              )}
              {state.status === 'empty' && (
                <Admonition type="default" title="Open a dashboard link">
                  <p>
                    Open a link generated by your agent, or try a recent hour of project metrics.
                    This view is not saved as a report.
                  </p>
                  <p>
                    Sign in before opening a generated link. If signing in removed the dashboard,
                    reopen the original link.
                  </p>
                </Admonition>
              )}
              {state.status === 'error' && (
                <Admonition type="warning" title="Unable to open dashboard link">
                  <p>{state.error.message}</p>
                  <p>Generate a new link or open the example below.</p>
                </Admonition>
              )}
              <div className="flex items-center gap-2">
                <Button
                  type="button"
                  variant="default"
                  loading={isOpeningExample}
                  onClick={handleOpenExample}
                >
                  Open example
                </Button>
                {state.status === 'ready' && (
                  <Button type="button" variant="outline" onClick={handleCopyLink}>
                    Copy link
                  </Button>
                )}
              </div>
              {state.status === 'ready' && (
                <>
                  <p className="text-sm text-foreground-light">
                    {dayjs(state.model.start).utc().format('YYYY-MM-DD HH:mm:ss')} to{' '}
                    {dayjs(state.model.end).utc().format('YYYY-MM-DD HH:mm:ss')} UTC ·{' '}
                    {state.model.interval} interval
                  </p>
                  {state.model.annotations.length > 0 && (
                    <section
                      aria-label="Agent annotations"
                      className="rounded-lg border p-4 space-y-2"
                    >
                      <h2 className="text-sm font-medium">Agent annotations</h2>
                      <ol className="space-y-2 text-sm">
                        {state.model.annotations.map(({ at, label }, index) => (
                          <li key={index} className="break-words">
                            <time dateTime={at} className="font-mono text-foreground-light">
                              {dayjs(at).utc().format('YYYY-MM-DD HH:mm:ss [UTC]')}
                            </time>{' '}
                            — {label}
                          </li>
                        ))}
                      </ol>
                    </section>
                  )}
                  <div className="grid grid-cols-1 gap-6 xl:grid-cols-2">
                    {state.model.panels.map((panel, index) => (
                      <ModelMetricPanel
                        key={index}
                        projectRef={projectRef}
                        model={state.model}
                        panel={panel}
                      />
                    ))}
                  </div>
                </>
              )}
            </div>
          </PageSectionContent>
        </PageSection>
      </PageContainer>
    </>
  )
}
