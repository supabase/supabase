import { useMemo } from 'react'

import { useExposedSchemasQuery } from '@/data/config/project-postgrest-config-query'
import { OpenAPISpecData, useOpenAPISpecQuery } from '@/data/open-api/api-spec-query'
import { partitionExposedDocsEntities } from '@/data/privileges/exposed-docs-entities'
import { useExposedFunctionsQuery } from '@/data/privileges/exposed-functions-query'
import { useExposedTablesQuery } from '@/data/privileges/exposed-tables-query'
import { useSelectedProjectQuery } from '@/hooks/misc/useSelectedProject'

const OPEN_API_SPEC_STALE_TIME = 1000 * 60 * 10

const selectTables = (spec: OpenAPISpecData | undefined) => spec?.tables ?? []
const selectFunctions = (spec: OpenAPISpecData | undefined) => spec?.functions ?? []

const useApiDocsEntities = <
  TSpecEntity extends { name: string; schema?: string },
  TExposedStatus extends {
    name: string
    schema?: string
    status: 'granted' | 'revoked' | 'custom'
  },
>(
  selectEntities: (spec: OpenAPISpecData | undefined) => TSpecEntity[],
  useExposedEntitiesQuery: (args: { projectRef?: string; connectionString?: string | null }) => {
    data: TExposedStatus[] | undefined
  }
) => {
  const { data: project } = useSelectedProjectQuery()
  const projectRef = project?.ref
  const {
    data: exposedSchemas,
    error: exposedSchemasError,
    isPending: isExposedSchemasPending,
    isSuccess: areSchemasReady,
  } = useExposedSchemasQuery({ projectRef })

  const {
    data: spec,
    error: openApiSpecError,
    isLoading: isSpecLoading,
  } = useOpenAPISpecQuery(
    { projectRef, schemas: exposedSchemas },
    { enabled: areSchemasReady, staleTime: OPEN_API_SPEC_STALE_TIME }
  )
  const { data: exposedEntities } = useExposedEntitiesQuery({
    projectRef,
    connectionString: project?.connectionString,
  })

  return useMemo(() => {
    const entities = spec ? selectEntities(spec) : []

    return {
      ...partitionExposedDocsEntities(entities, exposedEntities),
      error: exposedSchemasError || openApiSpecError,
      isLoading: isExposedSchemasPending || (areSchemasReady && isSpecLoading),
    }
  }, [
    spec,
    selectEntities,
    exposedEntities,
    exposedSchemasError,
    openApiSpecError,
    isExposedSchemasPending,
    areSchemasReady,
    isSpecLoading,
  ])
}

/**
 * Tables shown in the autogenerated Data API docs, with unexposed (revoked)
 * tables filtered out and counted.
 */
export const useApiDocsTables = () =>
  useApiDocsEntities(selectTables, ({ projectRef, connectionString }) =>
    useExposedTablesQuery({
      projectRef,
      connectionString,
    })
  )

/**
 * Database functions shown in the autogenerated Data API docs, with unexposed
 * (revoked) functions filtered out and counted.
 */
export const useApiDocsFunctions = () =>
  useApiDocsEntities(selectFunctions, ({ projectRef, connectionString }) =>
    useExposedFunctionsQuery({
      projectRef,
      connectionString,
    })
  )
