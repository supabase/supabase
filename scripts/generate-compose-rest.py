#!/usr/bin/env python3
"""
Generate docker-compose PostgREST service definitions from the database registry.
Usage: python3 scripts/generate-compose-rest.py > docker/docker-compose.rest.yml
"""
import json
import os

registry_path = os.environ.get(
    "DATABASE_REGISTRY_PATH",
    "docker/volumes/registry/databases.json"
)

with open(registry_path) as f:
    registry = json.load(f)

databases = registry["databases"]

print("# Auto-generated by scripts/generate-compose-rest.py")
print("# Do not edit manually - regenerate with: python3 scripts/generate-compose-rest.py")
print("version: '3.8'")
print("services:")

for db in databases:
    ref = db["ref"]
    password_env = db.get("password_env", "POSTGRES_PASSWORD")
    jwt_secret_env = db.get("jwt_secret_env", "JWT_SECRET")
    host = db.get("host", "db")
    port = db.get("port", 5432)
    database = db.get("database", "postgres")

    print(f"""
  rest-{ref}:
    container_name: supabase-rest-{ref}
    image: postgrest/postgrest:v12.2.9
    restart: unless-stopped
    depends_on:
      db:
        condition: service_healthy
    environment:
      PGRST_DB_URI: "postgres://authenticator:${{{password_env}}}@{host}:{port}/{database}"
      PGRST_DB_SCHEMAS: "${{PGRST_DB_SCHEMAS:-public,graphql_public}}"
      PGRST_DB_ANON_ROLE: anon
      PGRST_JWT_SECRET: ${{{jwt_secret_env}}}
      PGRST_DB_USE_LEGACY_GUCS: "false"
      PGRST_APP_SETTINGS_JWT_SECRET: ${{{jwt_secret_env}}}
      PGRST_APP_SETTINGS_JWT_EXP: "${{JWT_EXPIRY:-3600}}"
    command: "postgrest"
    networks:
      - supabase_network""")

print("""
networks:
  supabase_network:
    external: true
""")