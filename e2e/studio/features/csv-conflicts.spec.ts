import { randomUUID } from 'node:crypto'
import { expect } from '@playwright/test'

import { dropTable, query } from '../utils/db/index.js'
import { test, withSetupCleanup } from '../utils/test.js'
import { toUrl } from '../utils/to-url.js'
import { createApiResponseWaiter } from '../utils/wait-for-response.js'

for (const method of ['upload', 'paste']) {
  test(`CSV ${method} skips conflicts only when enabled and reports actual counts`, async ({
    page,
    ref,
  }) => {
    const tableName = `pw_csv_conflicts_${method}_${randomUUID().slice(0, 8)}`
    await using _ = await withSetupCleanup(
      () =>
        query(`drop table if exists public.${tableName}; create table public.${tableName} (
        id bigint generated by default as identity primary key,
        email text unique, note text check (note <> 'invalid')
      ); insert into public.${tableName} (id, email, note) values (1, 'existing', 'original');`),
      () => dropTable(tableName)
    )
    await page.goto(toUrl(`/project/${ref}/editor?schema=public`))
    await page.getByRole('button', { name: `View ${tableName}`, exact: true }).click()
    await page.waitForURL(/\/editor\/\d+\?schema=public$/)

    const csv = 'id,email,note\n1,existing,changed\n2,new,fresh\n3,new,duplicate\n4,other,fresh'
    const openImport = async (text: string) => {
      await page.getByRole('button', { name: 'Insert', exact: true }).click()
      await page.getByRole('menuitem', { name: 'Import data from CSV' }).click()
      if (method === 'upload') {
        await page.setInputFiles('input[type="file"]', {
          name: 'conflicts.csv',
          mimeType: 'text/csv',
          buffer: Buffer.from(text),
        })
      } else {
        await page.getByRole('tab', { name: 'Paste text' }).click()
        await page.getByRole('textbox', { name: 'CSV text' }).fill(text)
      }
      await expect(page.getByText(/rows? will be processed/)).toBeVisible()
      await page.getByRole('button', { name: 'Toggle import configuration' }).click()
    }
    await openImport(csv)
    const toggle = page.getByRole('switch', { name: 'Skip conflicting rows' })
    await expect(toggle, 'Conflict skipping must default off').not.toBeChecked()
    await page.getByRole('button', { name: 'Import data', exact: true }).click()
    await expect(
      page.getByText('0 rows imported, 0 skipped before the import stopped.', { exact: false }),
      'Default mode must fail the conflicting batch'
    ).toBeVisible()
    expect(await query(`select id, email, note from public.${tableName} order by id`)).toEqual([
      { id: 1, email: 'existing', note: 'original' },
    ])

    await toggle.focus()
    await page.keyboard.press('Space')
    await expect(toggle, 'The switch must support keyboard input').toBeChecked()
    const inserted = createApiResponseWaiter(page, 'pg-meta', ref, 'query?key=', { method: 'POST' })
    await page.keyboard.press('ControlOrMeta+Enter')
    await inserted
    await expect(
      page.getByText('2 rows imported, 2 skipped', { exact: true }),
      'Counts must reflect both unique and primary-key conflicts'
    ).toBeVisible()
    expect(await query(`select id, email, note from public.${tableName} order by id`)).toEqual([
      { id: 1, email: 'existing', note: 'original' },
      { id: 2, email: 'new', note: 'fresh' },
      { id: 4, email: 'other', note: 'fresh' },
    ])

    await openImport(csv)
    await expect(toggle, 'A new import session must reset conflict skipping').not.toBeChecked()
    await toggle.check()
    await page.getByRole('button', { name: 'Import data', exact: true }).click()
    await expect(
      page.getByText('0 rows imported, 4 skipped', { exact: true }),
      'Reimport must skip every row'
    ).toBeVisible()

    await openImport('id,email,note\n5,bad,invalid')
    await toggle.check()
    await page.getByRole('button', { name: 'Import data', exact: true }).click()
    await expect(
      page.getByText('check constraint', { exact: false }),
      'Other constraints must still fail'
    ).toBeVisible()
    expect(await query(`select count(*)::int as count from public.${tableName}`)).toEqual([
      { count: 3 },
    ])

    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
    const partialCSV = [
      'id,email,note',
      ...Array.from({ length: 3000 }, (_, index) =>
        [index + 10, `partial_${index}`, 'valid'.repeat(16)].join(',')
      ),
      '3010,last,invalid',
    ].join('\n')
    await openImport(partialCSV)
    await toggle.check()
    const refreshedRows = createApiResponseWaiter(page, 'pg-meta', ref, 'query?key=table-rows-', {
      method: 'POST',
    })
    await page.getByRole('button', { name: 'Import data', exact: true }).click()
    await expect(
      page.getByText(/^[1-9][\d,]* rows imported, 0 skipped before the import stopped\./),
      'A later batch failure must retain confirmed earlier inserts'
    ).toBeVisible()
    await refreshedRows
    const [{ count }] = await query<{ count: number }>(
      `select count(*)::int as count from public.${tableName}`
    )
    expect(count).toBeGreaterThan(3)
    await expect(
      page.getByText(
        `${(count - 3).toLocaleString()} rows imported, 0 skipped before the import stopped.`,
        {
          exact: false,
        }
      ),
      'Partial-progress feedback must agree with committed database rows'
    ).toBeVisible()
    await expect(page.getByRole('button', { name: 'Import data', exact: true })).toBeEnabled()

    const next = await query<{ id: number }>(
      `insert into public.${tableName} (email, note) values ('next', 'valid') returning id`
    )
    expect(next[0].id, 'The identity sequence must allow the next generated ID').toBeGreaterThan(4)
  })
}
