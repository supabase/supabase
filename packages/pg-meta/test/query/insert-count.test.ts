import { afterAll, beforeAll, beforeEach, describe, expect, test } from 'vitest'

import { ident, safeSql } from '../../src/pg-format'
import { insertQuery } from '../../src/query/Query.utils'
import { getImpersonationSQL } from '../../src/sql/studio/role-impersonation'
import { getUpdateIdentitySequenceSQL } from '../../src/sql/studio/table-editor/identity'
import { cleanupRoot, createTestDatabase } from '../db/utils'

let db: Awaited<ReturnType<typeof createTestDatabase>>
const table = { schema: 'public', name: 'imports' }

beforeAll(async () => {
  db = await createTestDatabase()
  await db.executeQuery(`create table imports (id int primary key, email text unique);
    create table default_imports (id int generated by default as identity primary key);`)
})

beforeEach(async () => {
  await db.executeQuery(`truncate imports, default_imports restart identity cascade;
    insert into imports values (1, 'existing')`)
})

afterAll(async () => {
  await db?.cleanup()
  await cleanupRoot()
})

describe('counted inserts', () => {
  test('preserves default SQL and fails the entire batch on conflicts', async () => {
    expect(insertQuery(table, [{ id: 1, email: 'existing' }])).toBe(
      `insert into public.imports (id,email) select id,email from jsonb_populate_recordset(null::public.imports, '[{"id":1,"email":"existing"}]');`
    )
    await expect(
      db.executeQuery(insertQuery(table, [{ id: 2 }, { id: 1 }], { returning: 'count' }))
    ).rejects.toThrow('duplicate key')
    expect(await db.executeQuery('select id from imports')).toEqual([{ id: 1 }])
  })

  test('counts PK, unique, same-batch and cross-batch conflicts without updating rows', async () => {
    const rows = [
      { id: 1, email: 'changed' },
      { id: 2, email: 'existing' },
      { id: 3, email: 'new' },
      { id: 3, email: 'duplicate' },
      { id: 4, email: 'other' },
    ]
    const sql = insertQuery(table, rows, { onConflict: 'ignore', returning: 'count' })
    expect(await db.executeQuery(sql)).toEqual([{ inserted_count: 2 }])
    expect(await db.executeQuery(sql)).toEqual([{ inserted_count: 0 }])
    expect(await db.executeQuery('select * from imports order by id')).toEqual([
      { id: 1, email: 'existing' },
      { id: 3, email: 'new' },
      { id: 4, email: 'other' },
    ])
  })

  test('supports row returns with conflict skipping', async () => {
    expect(
      await db.executeQuery(
        insertQuery(table, [{ id: 1 }, { id: 5 }], { onConflict: 'ignore', returning: true })
      )
    ).toEqual([{ id: 5, email: null }])
  })

  test('counts more than 1000 inserted rows in a single result row', async () => {
    const rows = Array.from({ length: 1100 }, (_, i) => ({ id: i + 100 }))
    expect(await db.executeQuery(insertQuery(table, rows, { returning: 'count' }))).toEqual([
      { inserted_count: rows.length },
    ])
  })

  test('supports composite keys, expression indexes, and NULL uniqueness', async () => {
    await db.executeQuery(`
      create table composite_imports (tenant int, id int, name text, primary key (tenant, id));
      create unique index on composite_imports (lower(name));
    `)
    expect(
      await db.executeQuery(
        insertQuery(
          { name: 'composite_imports', schema: 'public' },
          [
            { tenant: 1, id: 1, name: 'First' },
            { tenant: 1, id: 1, name: 'Other' },
            { tenant: 2, id: 1, name: 'FIRST' },
            { tenant: 3, id: 1, name: null },
            { tenant: 4, id: 1, name: null },
          ],
          { onConflict: 'ignore', returning: 'count' }
        )
      )
    ).toEqual([{ inserted_count: 3 }])
  })

  test('supports partitioned tables', async () => {
    await db.executeQuery(`
      create table partition_imports (id int primary key) partition by range (id);
      create table partition_imports_first partition of partition_imports for values from (0) to (10);
    `)
    expect(
      await db.executeQuery(
        insertQuery(
          { name: 'partition_imports', schema: 'public' },
          [{ id: 1 }, { id: 1 }, { id: 2 }],
          { onConflict: 'ignore', returning: 'count' }
        )
      )
    ).toEqual([{ inserted_count: 2 }])
  })

  test('quotes names and values, preserves JSON and arrays, and works without unique keys', async () => {
    await db.executeQuery(`create table "Odd'Table" ("Odd'Column" text, data jsonb, tags text[])`)
    const values = [
      { "Odd'Column": "'); drop table imports; --", data: { quote: "O'Reilly" }, tags: ['a', 'b'] },
    ]
    const target = { name: "Odd'Table", schema: 'public' }
    const sql = insertQuery(target, values, { returning: 'count', onConflict: 'ignore' })
    expect(await db.executeQuery(sql)).toEqual([{ inserted_count: 1 }])
    expect(await db.executeQuery(sql)).toEqual([{ inserted_count: 1 }])
    expect(await db.executeQuery(safeSql`select * from ${ident(target.name)}`)).toEqual([
      ...values,
      ...values,
    ])
  })

  test('preserves default columns when no columns are selected', async () => {
    expect(
      await db.executeQuery(
        insertQuery({ name: 'default_imports', schema: 'public' }, [{}, {}], {
          onConflict: 'ignore',
          returning: 'count',
        })
      )
    ).toEqual([{ inserted_count: 2 }])
  })

  test.each([
    ['type', "'bad'", 'invalid input syntax'],
    ['check', '-1', 'check constraint'],
    ['not null', 'null', 'not-null constraint'],
    ['foreign key', '99999', 'foreign key constraint'],
  ])('does not skip %s errors', async (_name, value, message) => {
    await db.executeQuery(`drop table if exists invalid_imports;
      create table invalid_imports (id int not null check (id > 0) references imports(id))`)
    const rows = [{ id: 1 }, { id: JSON.parse(value.replaceAll("'", '"')) }]
    await expect(
      db.executeQuery(
        insertQuery({ name: 'invalid_imports', schema: 'public' }, rows, {
          onConflict: 'ignore',
          returning: 'count',
        })
      )
    ).rejects.toThrow(message)
    expect(await db.executeQuery('select * from invalid_imports')).toEqual([])
  })

  test('counts inserts suppressed by a trigger as not inserted', async () => {
    await db.executeQuery(`create table trigger_imports (id int);
      create function suppress_import() returns trigger language plpgsql as $$
        begin if new.id = 0 then return null; end if; return new; end $$;
      create trigger suppress before insert on trigger_imports for each row execute function suppress_import()`)
    expect(
      await db.executeQuery(
        insertQuery({ name: 'trigger_imports', schema: 'public' }, [{ id: 0 }, { id: 1 }], {
          onConflict: 'ignore',
          returning: 'count',
        })
      )
    ).toEqual([{ inserted_count: 1 }])
  })

  test('supports INSERT-only roles and RLS without requiring SELECT privileges', async () => {
    const role = `import_${db.dbName}`
    try {
      await db.executeQuery(`create role ${role};
        create table rls_imports (id int primary key check (id > 0));
        alter table rls_imports enable row level security;
        create policy insert_allowed on rls_imports for insert to ${role} with check (id < 10);
        grant usage on schema public to ${role};
        grant insert on rls_imports to ${role}`)
      const executeAsRole = (rows: { id: number }[]) =>
        db.executeQuery(
          getImpersonationSQL({
            role: { type: 'custom', role },
            sql: insertQuery({ schema: 'public', name: 'rls_imports' }, rows, {
              onConflict: 'ignore',
              returning: 'count',
            }),
          })
        )
      expect(await executeAsRole([{ id: 1 }])).toEqual([{ inserted_count: 1 }])
      expect(await executeAsRole([{ id: 1 }])).toEqual([{ inserted_count: 0 }])
      await expect(executeAsRole([{ id: 2 }, { id: 10 }])).rejects.toThrow('row-level security')
      await db.executeQuery('reset role')
      expect(await db.executeQuery('select * from rls_imports')).toEqual([{ id: 1 }])
      await db.executeQuery(`revoke insert on rls_imports from ${role}`)
      await expect(executeAsRole([{ id: 3 }])).rejects.toThrow('permission denied')
    } finally {
      await db.executeQuery(`reset role; drop owned by ${role}; drop role ${role}`)
    }
  })

  test('surfaces deferrable constraint incompatibility', async () => {
    await db.executeQuery('create table deferred_imports (id int unique deferrable)')
    await expect(
      db.executeQuery(
        insertQuery({ name: 'deferred_imports', schema: 'public' }, [{ id: 1 }], {
          onConflict: 'ignore',
          returning: 'count',
        })
      )
    ).rejects.toThrow('does not support deferrable')
  })

  test('raises the sequence after importing explicit IDs', async () => {
    await db.executeQuery(
      insertQuery({ name: 'default_imports', schema: 'public' }, [{ id: 100 }], {
        returning: 'count',
      })
    )
    await db.executeQuery(
      getUpdateIdentitySequenceSQL({ schema: 'public', table: 'default_imports', column: 'id' })
    )
    expect(
      await db.executeQuery('insert into default_imports default values returning id')
    ).toEqual([{ id: 101 }])
  })

  test('does not lower the sequence below values already issued', async () => {
    await db.executeQuery(
      `select setval(pg_get_serial_sequence('public.default_imports', 'id'), 200)`
    )
    await db.executeQuery(
      insertQuery({ name: 'default_imports', schema: 'public' }, [{ id: 100 }], {
        returning: 'count',
      })
    )
    await db.executeQuery(
      getUpdateIdentitySequenceSQL({ schema: 'public', table: 'default_imports', column: 'id' })
    )
    expect(
      await db.executeQuery('insert into default_imports default values returning id')
    ).toEqual([{ id: 201 }])
  })

  test('leaves an unused sequence at its start when nothing was imported', async () => {
    await db.executeQuery(
      getUpdateIdentitySequenceSQL({ schema: 'public', table: 'default_imports', column: 'id' })
    )
    expect(
      await db.executeQuery('insert into default_imports default values returning id')
    ).toEqual([{ id: 1 }])
  })

  test('moves descending sequences past imported IDs', async () => {
    await db.executeQuery(`create table descending_imports (
      id int generated by default as identity (increment by -1 maxvalue -1 start with -1) primary key
    )`)
    const updateSequence = () =>
      db.executeQuery(
        getUpdateIdentitySequenceSQL({
          schema: 'public',
          table: 'descending_imports',
          column: 'id',
        })
      )
    await db.executeQuery('insert into descending_imports values (-1)')
    await updateSequence()
    expect(
      await db.executeQuery('insert into descending_imports default values returning id')
    ).toEqual([{ id: -2 }])
    await db.executeQuery('insert into descending_imports values (-1000)')
    await updateSequence()
    await db.executeQuery('delete from descending_imports where id = -1000')
    await updateSequence()
    expect(
      await db.executeQuery('insert into descending_imports default values returning id')
    ).toEqual([{ id: -1001 }])
  })
})
