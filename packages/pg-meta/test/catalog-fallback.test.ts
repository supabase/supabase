const byText = (key: string) => (a: any, b: any) =>
  String(a[key]) < String(b[key]) ? -1 : String(a[key]) > String(b[key]) ? 1 : 0
const sortRelationships = (relationships: any[]) =>
  [...relationships].sort(
    (a, b) =>
      a.id - b.id || byText('source_column_name')(a, b) || byText('target_column_name')(a, b)
  )

// What a partial catalog cannot know, as `catalog-fallback.ts` lists, and the enum labels the
// fallbacks do not read (Spark has no pg_enum).
const comparableTable = ({
  bytes,
  size,
  live_rows_estimate,
  dead_rows_estimate,
  relationships,
  columns,
  ...table
}: any) => ({
  ...table,
  relationships: sortRelationships(relationships),
  ...(columns && {
    columns: [...columns]
      .sort((a: any, b: any) => a.ordinal_position - b.ordinal_position)
      .map(({ enums, ...column }: any) => column),
  }),
})
const comparableTables = (tables: any[]) => tables.map(comparableTable).sort((a, b) => a.id - b.id)

describe('tables list, retrieve and paginated list', () => {
  postgresTest('the fallbacks return what the pg-meta queries return', async (query) => {
    for (const options of [
      { includeColumns: false },
      { includeColumns: true, includedSchemas: ['public'] },
      { includeColumns: true, excludedSchemas: ['public'] },
    ]) {
      const expected = comparableTables(await query(pgMeta.tables.list(options).sql))
      expect(expected.length).toBeGreaterThan(0)
      expect(comparableTables(await listTablesFallback(query, options))).toEqual(expected)
    }

    for (const identifier of [
      { schema: 'public', name: 'authors' },
      { schema: 'public', name: 'pair_notes' },
      { schema: 'public', name: 'events' },
    ]) {
      const [expected] = await query(pgMeta.tables.retrieve(identifier).sql)
      const actual = await retrieveTableFallback(query, identifier)
      expect(actual?.relationships).toEqual(expected.relationships)
      expect(comparableTable(actual)).toEqual(comparableTable(expected))
    }
    expect(
      await retrieveTableFallback(query, { schema: 'public', name: 'missing' })
    ).toBeUndefined()

    for (const options of [
      { schema: 'public', limit: 50, afterOid: 0 },
      { schema: 'public', limit: 2, afterOid: 0, includeColumns: true },
      { limit: 50, afterOid: 0, nameFilter: 'pair' },
    ]) {
      const expected = comparableTables(await query(getTablesPaginatedSql(options)))
      expect(expected.length).toBeGreaterThan(0)
      expect(comparableTables(await listTablesPaginatedFallback(query, options))).toEqual(expected)
    }
  })

  sparkTest('the fallbacks describe the tables, keys and relationships', async (query) => {
    const tables = await sparkFallback(
      pgMeta.tables.list({ includedSchemas: ['public'], includeColumns: true }).sql,
      () => listTablesFallback(query, { includedSchemas: ['public'], includeColumns: true })
    )
    const relationship = {
      constraint_name: 'posts_author_id_fkey',
      source_schema: 'public',
      source_table_name: 'posts',
      source_column_name: 'author_id',
      target_table_schema: 'public',
      target_table_name: 'authors',
      target_column_name: 'id',
    }
    expect(tables.map((t) => t.name).sort()).toEqual(['authors', 'posts'])
    expect(tables.find((t) => t.name === 'posts')).toMatchObject({
      rls_enabled: true,
      replica_identity: 'DEFAULT',
      live_rows_estimate: 0,
      primary_keys: [{ schema: 'public', table_name: 'posts', name: 'id' }],
      relationships: [relationship],
      columns: [
        { name: 'id', format: 'int8', is_identity: true, identity_generation: 'BY DEFAULT' },
        { name: 'author_id', format: 'int8', is_nullable: true },
        { name: 'title', format: 'text', is_unique: true, is_nullable: false },
        { name: 'body', format: 'text' },
      ],
    })
    expect(tables.find((t) => t.name === 'authors')).toMatchObject({
      rls_enabled: false,
      relationships: [relationship],
      columns: expect.arrayContaining([
        expect.objectContaining({ name: 'active', format: 'bool', default_value: 'true' }),
        expect.objectContaining({ name: 'meta', format: 'jsonb', data_type: 'jsonb' }),
      ]),
    })

    const retrieved = await sparkFallback(
      pgMeta.tables.retrieve({ schema: 'public', name: 'posts' }).sql,
      () => retrieveTableFallback(query, { schema: 'public', name: 'posts' })
    )
    expect(comparableTable(retrieved)).toEqual(
      comparableTable(tables.find((t) => t.name === 'posts'))
    )

    const page = await sparkFallback(
      getTablesPaginatedSql({ schema: 'public', limit: 1, afterOid: 0 }),
      () => listTablesPaginatedFallback(query, { schema: 'public', limit: 1, afterOid: 0 })
    )
    expect(page).toHaveLength(1)
    expect(page[0]).not.toHaveProperty('columns')
  })
})

