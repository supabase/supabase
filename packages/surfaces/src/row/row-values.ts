import { displayValue, errorMessage } from '../common'
import type { Column, Row, Table } from '../contract'

/** How a field is written: a typed value, an explicit NULL, or the database default. */
export type FieldMode = 'value' | 'null' | 'default'
export interface FieldDraft {
  raw: string
  mode: FieldMode
}
export type RowDraft = Record<string, FieldDraft>

const JSON_FORMATS = ['json', 'jsonb']
const INTEGER_FORMATS = ['int2', 'int4', 'int8']
const DECIMAL_FORMATS = ['numeric', 'float4', 'float8']

export const isJsonColumn = (column: Column) => JSON_FORMATS.includes(column.format)

/** Converts form text to the value sent to the database, or throws a message for the field. */
export function parseCellValue(column: Column, raw: string, isNull: boolean): unknown {
  if (isNull) {
    if (!column.nullable) throw new Error('This column does not allow NULL.')
    return null
  }
  if (isJsonColumn(column)) return JSON.parse(raw)
  if (column.format.startsWith('_') || column.data_type === 'ARRAY') {
    const value: unknown = JSON.parse(raw)
    if (!Array.isArray(value)) throw new Error('Enter a JSON array.')
    return value
  }
  if (column.format === 'bool') {
    if (raw !== 'true' && raw !== 'false') throw new Error('Enter true or false.')
    return raw === 'true'
  }
  if (INTEGER_FORMATS.includes(column.format) && !/^[+-]?\d+$/.test(raw)) {
    throw new Error('Enter a whole number.')
  }
  if (
    DECIMAL_FORMATS.includes(column.format) &&
    !/^[+-]?(?:\d+\.?\d*|\.\d+)(?:e[+-]?\d+)?$/i.test(raw)
  ) {
    throw new Error('Enter a number.')
  }
  // Numeric values remain strings so int8 / decimal values do not lose precision.
  return raw
}

function initialMode(column: Column, row?: Row): FieldMode {
  if (row) return row[column.name] === null ? 'null' : 'value'
  // New rows leave defaults and generated values to the database.
  if (column.generated || column.default_value != null) return 'default'
  return column.nullable ? 'null' : 'value'
}

export function initialRowDraft(table: Table, row?: Row): RowDraft {
  return Object.fromEntries(
    table.columns.map((column) => [
      column.name,
      {
        raw: row?.[column.name] == null ? '' : displayValue(row[column.name]),
        mode: initialMode(column, row),
      },
    ])
  )
}

export const isFieldChanged = (a?: FieldDraft, b?: FieldDraft) =>
  a?.raw !== b?.raw || a?.mode !== b?.mode

/** Inserts can write anything a new row may set; updates never touch keys or identity columns. */
export function canEditColumn(table: Table, column: Column, isWritable: boolean, row?: Row) {
  if (!isWritable || !column.editable || column.generated) return false
  if (!row) return true
  return !column.identity && !table.primary_keys.includes(column.name)
}

/** A row can be written when the table allows it and an existing row has a complete primary key. */
export function isRowWritable(table: Table, readOnly: boolean, row?: Row) {
  if (readOnly || !table.editable) return false
  if (!row) return true
  return table.primary_keys.length > 0 && table.primary_keys.every((key) => row[key] != null)
}

export function defaultHint(column: Column) {
  if (column.generated) return 'Generated by the database'
  if (column.default_value != null) return `Default: ${String(column.default_value)}`
  if (column.nullable) return 'Defaults to NULL'
  return 'A value is required unless a database trigger provides one'
}

/**
 * The values to write. Updates send only changed fields; inserts omit fields
 * left on Default so the database fills them. Field errors name the column.
 */
export function buildRowValues(
  table: Table,
  draft: RowDraft,
  changedColumns: Column[],
  isWritable: boolean,
  row?: Row
): Row {
  const fields = row
    ? changedColumns
    : table.columns.filter((column) => draft[column.name].mode !== 'default')
  return Object.fromEntries(
    fields
      .filter((column) => canEditColumn(table, column, isWritable, row))
      .map((column) => {
        const field = draft[column.name]
        try {
          return [column.name, parseCellValue(column, field.raw, field.mode === 'null')]
        } catch (error) {
          throw new Error(`${column.name}: ${errorMessage(error)}`)
        }
      })
  )
}

/** The complete primary key of an existing row. */
export const rowKey = (table: Table, row: Row): Row =>
  Object.fromEntries(table.primary_keys.map((key) => [key, row[key]]))
